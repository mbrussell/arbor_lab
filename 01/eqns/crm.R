
# BOLEHT not provided for every tree. Need to predict it using variables we have.
library(nlme)

obs  <- tree |> 
  filter(!is.na(BOLEHT)) |> 
  filter(if_all(c(BOLEHT, ACTUALHT, DIA, CR, SPCD), \(x) !is.na(x))) |>
  mutate(SPCD = droplevels(factor(SPCD)))

miss <- tree |> filter(is.na(BOLEHT))

fit_boleht <- nlme(
  BOLEHT ~ ACTUALHT / (1 + exp(b0 + b1 * DIA + b2 * CR)),
  data    = obs,
  fixed   = b0 + b1 + b2 ~ 1,
  random  = b0 ~ 1 | SPCD,
  start   = c(b0 = 1, b1 = -0.1, b2 = 0.01),
  control = nlmeControl(maxIter = 200, msMaxIter = 200, pnlsTol = 0.01)
)

summary(fit_boleht)

sp_known <- levels(obs$SPCD)

tree <- tree |>
  mutate(
    BOLEHT_obs = BOLEHT,   # keep the original measurements
    can_pred   = is.na(BOLEHT) &
                 if_all(c(ACTUALHT, DIA, CR, SPCD), \(x) !is.na(x)),
    sp_seen    = as.character(SPCD) %in% sp_known,
    BOLEHT_imp = FALSE
  )

idx1 <- which(tree$can_pred &  tree$sp_seen)   # species-specific (level == 1)
idx0 <- which(tree$can_pred & !tree$sp_seen)   # population-level (level == 0)

if (length(idx1) > 0) {
  nd1 <- tree[idx1, ] |> mutate(SPCD = factor(SPCD, levels = sp_known))
  tree$BOLEHT[idx1] <- predict(fit_boleht, newdata = nd1, level = 1)
}
if (length(idx0) > 0) {
  nd0 <- tree[idx0, ] |> select(-SPCD)
  tree$BOLEHT[idx0] <- predict(fit_boleht, newdata = nd0, level = 0)
}
tree$BOLEHT_imp[c(idx1, idx0)] <- TRUE

