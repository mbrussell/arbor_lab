# 1. Gross volume
calc_VOLCFGRS <- function(SPCD, DBH, BOLE_HT, B0, B1, B2, B3, B4, B5) {
   VOLCFGRS = ifelse(is.na(BOLE_HT), NA,
                    B0 + (B1*DBH**B2) + (B3*DBH**B4*BOLE_HT**B5)) 
  return(VOLCFGRS)
  }

# 2. Sound volume
calc_VOLCFSND <- function(PCT_ROTTEN, VOLCFGRS){
  PCT_ROTTEN = ifelse(is.na(PCT_ROTTEN), 0,
                      ifelse(PCT_ROTTEN > 98, 100, PCT_ROTTEN))
  VOLCFSND = VOLCFGRS*(1-(PCT_ROTTEN/100))
  return(VOLCFSND)
  } 

# 3. Bole biomass (DRYBIO_BOLE)
calc_DRYBIO_BOLE <- function(SPCD, VOLCFSND, WOOD_SPGR_GREENVOL_DRYWT, BARK_VOL_PCT,
                     BARK_SPGR_GREENVOL_DRYWT){
  DRYBIO_BOLEWOOD <- VOLCFSND*WOOD_SPGR_GREENVOL_DRYWT*62.4
  DRYBIO_BOLEBARK <- VOLCFSND*(BARK_VOL_PCT/100)*BARK_SPGR_GREENVOL_DRYWT*62.4
  DRYBIO_BOLE <- DRYBIO_BOLEWOOD + DRYBIO_BOLEBARK 
  return(DRYBIO_BOLE)
  } 

